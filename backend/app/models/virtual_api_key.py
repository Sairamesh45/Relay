"""Virtual API Key model for external client authentication against the gateway."""

import uuid
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any

from sqlalchemy import Boolean, DateTime, ForeignKey, Index, String
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.gateway_request_log import GatewayRequestLog
    from app.models.rate_limit import RateLimitBucket
    from app.models.routing_policy import VirtualKeyRoutingPolicy
    from app.models.user import User


class VirtualAPIKey(Base):
    """Virtual API Key generated by users to authenticate external OpenAI-compatible client requests.

    Never stores the plaintext key. Stores only the non-secret prefix and HMAC-SHA256 hash.
    """

    __tablename__ = "virtual_api_keys"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )
    key_prefix: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        index=True,
    )
    key_hash: Mapped[str] = mapped_column(
        String(64),
        unique=True,
        index=True,
        nullable=False,
    )
    permissions: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        server_default="{}",
        nullable=False,
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        server_default="true",
        nullable=False,
        index=True,
    )
    last_used_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )
    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        back_populates="virtual_api_keys",
    )
    request_logs: Mapped[list["GatewayRequestLog"]] = relationship(
        "GatewayRequestLog",
        back_populates="virtual_api_key",
    )
    rate_limit_bucket: Mapped["RateLimitBucket | None"] = relationship(
        "RateLimitBucket",
        back_populates="virtual_api_key",
        cascade="all, delete-orphan",
        uselist=False,
    )
    routing_policy: Mapped["VirtualKeyRoutingPolicy | None"] = relationship(
        "VirtualKeyRoutingPolicy",
        back_populates="virtual_api_key",
        cascade="all, delete-orphan",
        uselist=False,
        lazy="selectin",
    )

    __table_args__ = (
        Index("ix_virtual_api_keys_prefix_active", "key_prefix", "is_active"),
        Index("ix_virtual_api_keys_user_active", "user_id", "is_active"),
    )
